package ret.tawny.truthful.utils.math;

public final class SensitivityUtil {

    public static final int MIN_PERCENT = 0;
    public static final int MAX_PERCENT = 200;

    private SensitivityUtil() {}

    /**
     * Calculates the Greatest Common Divisor (GCD) of two floating point numbers.
     * Used to find the minimum rotation 'step' the client can make.
     */
    public static double getGcd(double a, double b) {
        if (a < b) return getGcd(b, a);
        if (Math.abs(b) < 0.001) return a;
        return getGcd(b, a - Math.floor(a / b) * b);
    }

    /**
     * Returns the rotation step generated by a vanilla sensitivity slider value.
     * Minecraft applies this value to each raw mouse-count delta before sending a
     * rotation packet.
     */
    public static double getStepForSensitivityPercent(int percent) {
        int clamped = Math.max(MIN_PERCENT, Math.min(MAX_PERCENT, percent));
        double sensitivity = clamped / 200.0D;
        double f = sensitivity * 0.6D + 0.2D;
        return f * f * f * 1.2D;
    }

    /**
     * Converts a raw rotation step into the closest vanilla sensitivity slider
     * value. Invalid steps remain unresolved instead of being coerced to 0%,
     * which previously made low-confidence samples look like a real setting.
     */
    public static int getSensitivityFromPitchGCD(float deltaPitch) {
        if (!Float.isFinite(deltaPitch) || deltaPitch <= 0.0F) {
            return -1;
        }

        double f = Math.cbrt(deltaPitch / 1.2);
        double sensitivity = (f - 0.2) / 0.6;
        int percent = (int) Math.round(sensitivity * 200.0);

        if (percent < MIN_PERCENT || percent > MAX_PERCENT) return -1;
        return percent;
    }
}
